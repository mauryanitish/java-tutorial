public class TypeCasting {
    public static void main(String a[]){
        byte b = 127;
        int num = 278;
        b = (byte) num;
        System.out.println(b);

        float f = 29.8f;
        num = (int)f;
        System.out.println(num);

        char c ='t';
        c= (char)num;
        System.out.println(c);
    }
    
}
